const { chromium } = require("playwright");
const path=require("path"), fs=require("fs");
const HARNESS='window.__oly=()=>({st,setMode,setCam,drawMap,drawDisc,drawGlobe,map,mctx,CAM,OC,ocDrawField,ocDrawLimbs,ocPutDisc,ocPutGlobe,globeBasis,globeLUT,globeShell,GN_STILL,GN_MOVE,drawDeckBase,drawDeckLive,drawSchematicLayers,drawStations,EX,gpath,pathRings,GEO,OFF,CURF});\n';
const ANCHOR="\nrequestAnimationFrame(frame);\n})();\n</script>";
(async()=>{
  const file=process.argv[2];
  const raw=fs.readFileSync(file,"utf8");
  const p=path.join("build/shots","prof.html");
  fs.writeFileSync(p, raw.replace(ANCHOR,"\nrequestAnimationFrame(frame);\n"+HARNESS+"})();\n</script>"));
  const b=await chromium.launch({executablePath:"/opt/pw-browsers/chromium"});
  const pg=await b.newPage({viewport:{width:1440,height:900},deviceScaleFactor:2});
  await pg.goto("file://"+path.resolve(p),{waitUntil:"load",timeout:120000});
  await pg.waitForFunction("window.__oly",null,{timeout:60000});
  await pg.waitForTimeout(5000);
  const out=await pg.evaluate(async()=>{
    const A=window.__oly();
    const time=(fn,n)=>{ const t0=performance.now(); for(let i=0;i<n;i++) fn(); return (performance.now()-t0)/n; };
    const g=A.mctx, w=A.map.clientWidth, h=A.map.clientHeight;
    const r={};
    A.setMode("S"); A.drawMap();
    const s=Math.min(w,h)/2*0.93, cx=w/2, cy=h/2;
    r.canvas=[A.map.width,A.map.height];
    r.drawMapDisc = time(()=>A.drawMap(), 12);
    r.deckBase    = time(()=>A.drawDeckBase(g,cx,cy,s,true), 12);
    r.deckLive    = time(()=>A.drawDeckLive(g,cx,cy,s,true), 12);
    r.schematic   = time(()=>A.drawSchematicLayers(g,cx,cy,s,true,A.GEO.ant), 12);
    r.rings       = time(()=>{A.pathRings(g,A.GEO.ant,cx,cy,s,true); g.stroke();}, 12);
    r.shelf       = time(()=>{A.pathRings(g,A.GEO.shelf,cx,cy,s,false); g.fill();}, 12);
    r.iceImg      = time(()=>g.drawImage(A.OFF.sh,cx-s,cy-s,s*2,s*2), 12);
    r.flowDisc    = time(()=>A.ocDrawField(g,A.ocPutDisc(cx,cy,s,true)), 12);
    r.clearAll    = time(()=>g.clearRect(0,0,w,h), 12);
    A.setMode("GLOBE"); A.CAM.zoom=1; A.drawMap();
    const B=A.globeBasis(A.st.glat,A.st.glon);
    r.drawMapGlobe= time(()=>A.drawMap(), 12);
    r.lutStill    = (()=>{ let t=0,n=6; for(let i=0;i<n;i++){ const t0=performance.now(); A.globeLUT(A.GN_STILL, 10+i*0.37, 20+i*0.53); t+=performance.now()-t0; } return t/n; })();
    r.lutMove     = (()=>{ let t=0,n=6; for(let i=0;i<n;i++){ const t0=performance.now(); A.globeLUT(A.GN_MOVE, 30+i*0.37, 40+i*0.53); t+=performance.now()-t0; } return t/n; })();
    r.shell       = time(()=>A.globeShell("near",A.GN_STILL), 8);
    r.flowGlobe   = time(()=>A.ocDrawField(g,A.ocPutGlobe(B,cx,cy,s)), 12);
    r.limbsGlobe  = time(()=>A.ocDrawLimbs(g,B,cx,cy,s,1,0.3), 12);
    r.coastGlobe  = time(()=>{ g.beginPath(); for(const ring of A.EX.coast) A.gpath(g,ring,B,cx,cy,s,true); g.stroke(); }, 12);
    r.particles=A.OC.nPart; r.coastRings=A.EX.coast.length;
    r.coastPts=A.EX.coast.reduce((a,c)=>a+c.length/2,0);
    return r;
  });
  await b.close();
  for(const [k,v] of Object.entries(out)) console.log(String(k).padEnd(16), typeof v==="number"?v.toFixed(2)+" ms":JSON.stringify(v));
})();
